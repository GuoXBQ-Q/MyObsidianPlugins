import esbuild from "esbuild";
import process from "process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the source files under src/
*/`;

const production = process.argv[2] === "production";

await esbuild.build({
	absWorkingDir: root,
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: ["obsidian", "electron", "@codemirror/autocomplete", "@codemirror/collab", "@codemirror/commands", "@codemirror/language", "@codemirror/lint", "@codemirror/search", "@codemirror/state", "@codemirror/view", "@lezer/common", "@lezer/highlight", "@lezer/lr"],
	outfile: "build/main.js",
	format: "cjs",
	target: "es2020",
	logLevel: "info",
	sourcemap: production ? false : "inline",
	treeShaking: true,
	minify: production,
	banner: { js: banner },
});

for (const name of ["manifest.json", "styles.css"]) {
	fs.copyFileSync(path.join(root, name), path.join(root, "build", name));
}
