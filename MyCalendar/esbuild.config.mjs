import esbuild from "esbuild";
import process from "process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the source files under src/
*/`;

const production = process.argv[2] === "production";

await esbuild.build({
	absWorkingDir: root,
	entryPoints: ["src/main.ts"],
	bundle: true,
	// Keep desktop updater builtins as lazy runtime imports.
	platform: "node",
	external: ["obsidian", "electron", "@codemirror/autocomplete", "@codemirror/collab", "@codemirror/commands", "@codemirror/language", "@codemirror/lint", "@codemirror/search", "@codemirror/state", "@codemirror/view", "@lezer/common", "@lezer/highlight", "@lezer/lr"],
	outfile: "build/main.js",
	format: "cjs",
	target: "es2020",
	logLevel: "info",
	sourcemap: production ? false : "inline",
	treeShaking: true,
	minify: production,
	banner: { js: banner },
});

fs.copyFileSync(path.join(root, "manifest.json"), path.join(root, "build/manifest.json"));
fs.writeFileSync(path.join(root, "build/styles.css"),
	fs.readFileSync(path.join(root, "styles.css"), "utf8") + "\n" +
	fs.readFileSync(path.join(root, "../shared/plugin-updater.css"), "utf8"));
